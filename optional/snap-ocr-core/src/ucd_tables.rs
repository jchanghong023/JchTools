fn in_ranges(ranges: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    ranges
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                std::cmp::Ordering::Greater
            } else if cp > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// East Asian Width 为 W 或 F。
pub fn is_wide_or_fullwidth(c: char) -> bool {
    in_ranges(WIDE_OR_FULLWIDTH_RANGES, c)
}

/// 规范化组合类（ccc）非零。
pub fn has_combining_class(c: char) -> bool {
    in_ranges(NONZERO_COMBINING_RANGES, c)
}
